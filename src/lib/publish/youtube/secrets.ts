/**
 * SERVER-ONLY. The envelope every stored credential goes into.
 *
 * A YouTube refresh token is a long-lived credential: it can mint an access
 * token that uploads to the operator's channel, for months, without anyone
 * signing in again. Keeping one in a SQLite column in the clear means a copied
 * `dev.db` — a backup, a support ZIP, the `.superpowers/.../backup/` folder
 * this very workstream writes into — is a copy of the operator's channel. So
 * nothing credential-shaped is written to the database as plaintext.
 *
 * AES-256-GCM, with the key in `BOOKREEL_TOKEN_KEY` and nowhere else.
 *
 * WHY GCM AND NOT CBC: it is authenticated. A ciphertext that has been edited,
 * truncated, or moved between rows fails to decrypt rather than decrypting to
 * something else, and `open()` reports that as "reconnect" rather than sending
 * a corrupted token to Google and trying to interpret the refusal.
 *
 * WHY THE AAD MATTERS. Every seal is bound to a purpose string and the user it
 * belongs to (`youtube:refresh:<userId>`). Copying `refreshTokenEnc` from one
 * `PlatformAccount` row into another user's row therefore does not grant that
 * user the first one's channel — the tag check fails. Without AAD, row-level
 * copying would be a working privilege escalation inside one database.
 *
 * WHAT IS DELIBERATELY NOT HERE:
 *  - No fallback to plaintext when the key is missing. `keyStatus()` says the
 *    install is not configured, `isConfigured()` answers false, and the Publish
 *    Center shows REQUIRES_CONNECTION. An install that cannot protect a token
 *    does not get to hold one.
 *  - No logging of inputs or outputs, ever. `redact()` is the only thing in
 *    this module that produces a loggable string, and what it produces cannot
 *    be turned back into a token.
 */
import crypto from "node:crypto";

/**
 * What every function in this integration reads its configuration from.
 *
 * It is `Record<string, string | undefined>` and NOT `NodeJS.ProcessEnv`, which
 * this project's TypeScript narrows with required keys — so a test could not
 * pass a four-variable object without inventing a `NODE_ENV`. Every function
 * here takes it as a parameter defaulting to `process.env`, which is what makes
 * "an install with no key cannot hold a credential" a test rather than a claim.
 */
export type EnvLike = Record<string, string | undefined>;

/** The env var that holds the key. Named once, so nothing can read a near-miss. */
export const TOKEN_KEY_ENV = "BOOKREEL_TOKEN_KEY";

const ALGO = "aes-256-gcm";
const IV_BYTES = 12; // GCM's standard nonce size
const TAG_BYTES = 16;
const VERSION = "v1";

/**
 * A fixed salt for the scrypt fallback.
 *
 * A per-install random salt would be better cryptography and worse engineering
 * here: it would have to be stored beside the ciphertext, and an operator who
 * moved `dev.db` without it would find every token undecryptable with the
 * correct key. The key is already the secret; the salt's job in this fallback is
 * only domain separation, and a constant does that.
 *
 * It is only reached when the key is NOT 32 raw bytes — see `keyFrom`.
 */
const SCRYPT_SALT = "bookreel/publish/token/v1";

export class TokenKeyMissing extends Error {
  constructor(message: string) {
    super(message);
    this.name = "TokenKeyMissing";
  }
}

export class TokenUnreadable extends Error {
  constructor(message: string) {
    super(message);
    this.name = "TokenUnreadable";
  }
}

/**
 * 32 bytes from whatever the operator put in the variable.
 *
 * Accepted, in order: 64 hex characters, or a base64/base64url string that
 * decodes to exactly 32 bytes (what `openssl rand -base64 32` produces). Both
 * are used verbatim — a key generated by a CSPRNG should not be run through a
 * KDF that only loses entropy to no purpose.
 *
 * Anything else that is at least 32 characters is scrypt-derived, so an
 * operator who typed a long passphrase gets a working install rather than an
 * error they have to go and read code to understand. Shorter than that is
 * refused outright: a six-character "key" protects nothing and silently
 * accepting one would be the dishonest option.
 */
function keyFrom(raw: string): Buffer {
  const value = raw.trim();
  if (value === "") {
    throw new TokenKeyMissing(
      `${TOKEN_KEY_ENV} is not set, so stored platform tokens cannot be encrypted. ` +
        "Generate one with `openssl rand -base64 32` and set it in the environment.",
    );
  }

  if (/^[0-9a-fA-F]{64}$/.test(value)) return Buffer.from(value, "hex");

  if (/^[A-Za-z0-9+/_-]+={0,2}$/.test(value)) {
    const decoded = Buffer.from(value, "base64");
    if (decoded.length === 32) return decoded;
  }

  if (value.length < 32) {
    throw new TokenKeyMissing(
      `${TOKEN_KEY_ENV} is too short to protect a credential. Use 32 random bytes ` +
        "(`openssl rand -base64 32`), or a passphrase of at least 32 characters.",
    );
  }
  return crypto.scryptSync(value, SCRYPT_SALT, 32);
}

/** Read the key from the environment. Throws `TokenKeyMissing` when it cannot. */
function currentKey(env: EnvLike = process.env): Buffer {
  return keyFrom(env[TOKEN_KEY_ENV] ?? "");
}

/**
 * Is this install able to hold a credential at all, and if not, why not?
 *
 * Returns rather than throws, because the answer is a UI state
 * (REQUIRES_CONNECTION, with the reason printed) and not an error. The reason
 * names the variable; it never contains any part of its value.
 */
export function keyStatus(env: EnvLike = process.env): { ok: boolean; reason: string | null } {
  try {
    currentKey(env);
    return { ok: true, reason: null };
  } catch (err) {
    return { ok: false, reason: err instanceof Error ? err.message : String(err) };
  }
}

/**
 * Encrypt `plaintext` so that only this install's key, and only for this
 * purpose and this user, can read it back.
 *
 * The output is `v1.<iv>.<tag>.<ciphertext>`, all base64url. The version prefix
 * is there so a future key rotation or algorithm change can read old rows
 * instead of orphaning them.
 */
export function seal(plaintext: string, aad: string, env: EnvLike = process.env): string {
  const key = currentKey(env);
  const iv = crypto.randomBytes(IV_BYTES);
  const cipher = crypto.createCipheriv(ALGO, key, iv, { authTagLength: TAG_BYTES });
  cipher.setAAD(Buffer.from(aad, "utf8"));
  const body = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final()]);
  const tag = cipher.getAuthTag();
  return [VERSION, iv.toString("base64url"), tag.toString("base64url"), body.toString("base64url")].join(".");
}

/**
 * Read a sealed value back, or throw `TokenUnreadable`.
 *
 * Every failure mode lands on the same exception on purpose: a wrong key, a
 * truncated column, a tampered tag and an AAD mismatch are indistinguishable to
 * a caller and all mean the same thing operationally — this credential cannot
 * be used, so ask the operator to reconnect. The message says which, for the
 * operator's benefit, without quoting any bytes.
 */
export function open(sealed: string, aad: string, env: EnvLike = process.env): string {
  const parts = sealed.split(".");
  if (parts.length !== 4 || parts[0] !== VERSION) {
    throw new TokenUnreadable("This stored credential is not in a format this app wrote. Reconnect the account.");
  }
  let key: Buffer;
  try {
    key = currentKey(env);
  } catch (err) {
    // A missing key is a configuration problem, not a corrupt row, and the two
    // get different sentences because they have different fixes.
    throw new TokenKeyMissing(err instanceof Error ? err.message : String(err));
  }

  try {
    const iv = Buffer.from(parts[1], "base64url");
    const tag = Buffer.from(parts[2], "base64url");
    const body = Buffer.from(parts[3], "base64url");
    if (iv.length !== IV_BYTES || tag.length !== TAG_BYTES) {
      throw new Error("bad envelope");
    }
    const decipher = crypto.createDecipheriv(ALGO, key, iv, { authTagLength: TAG_BYTES });
    decipher.setAAD(Buffer.from(aad, "utf8"));
    decipher.setAuthTag(tag);
    return Buffer.concat([decipher.update(body), decipher.final()]).toString("utf8");
  } catch {
    throw new TokenUnreadable(
      `This stored credential could not be decrypted. Either ${TOKEN_KEY_ENV} has changed ` +
        "or the stored value was altered. Disconnect and reconnect the account.",
    );
  }
}

/** The AAD for one user's refresh token. */
export const refreshAad = (userId: string): string => `youtube:refresh:${userId}`;
/** The AAD for one user's cached access token. */
export const accessAad = (userId: string): string => `youtube:access:${userId}`;
/** The AAD for one in-flight authorisation's PKCE verifier. */
export const verifierAad = (userId: string): string => `youtube:pkce:${userId}`;
/** The AAD for one episode's resumable upload session URL. */
export const sessionAad = (episodeId: string): string => `youtube:session:${episodeId}`;

/**
 * The ONLY representation of a secret that may appear in a log line, an error
 * message, or a response body.
 *
 * It keeps the length and a short digest, which is enough to tell "the same
 * token as before" from "a different one" while debugging, and is not enough to
 * use. Nothing in this integration logs a token by any other route — and there
 * is no overload that takes a token and returns it.
 */
export function redact(secret: string | null | undefined): string {
  if (typeof secret !== "string" || secret === "") return "(none)";
  const digest = crypto.createHash("sha256").update(secret).digest("hex").slice(0, 8);
  return `(redacted ${secret.length} chars, sha256:${digest})`;
}
